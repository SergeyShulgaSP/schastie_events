def main():
    db = sqlite3.connect(os.path.join(ROOT, "data", "amo.sqlite"), timeout=120)
    texts = collections.defaultdict(list)
    skip = re.compile(r"^(Выбер|Additional information|Заявка |Какую технику|whatsapp:|Мини.*SKU|.*Shipping:)", re.S)
    for lid, t in db.execute("SELECT lead_id,text FROM lead_notes WHERE note_type='common' AND created_by!=0"):
        if t and not skip.match(t.strip()): texts[lid].append(t)
    for lid, t in db.execute("SELECT entity_id,json_extract(result,'$.text') FROM tasks WHERE entity_type='leads'"):
        if t: texts[lid].append(t)
    for lid, t in db.execute("SELECT lead_id,text FROM transcripts WHERE text IS NOT NULL"):
        texts[lid].append(t)
    for m, c, t in db.execute("SELECT messenger,chat_id,text FROM ca_messages WHERE side='in' AND text!=''"):
        texts["chat:" + m + c].append(t)
    joined = {k: "\n".join(v).lower() for k, v in texts.items()}
    rows = []
    for topic, q, a, rx in KB:
        n = sum(1 for t in joined.values() if re.search(rx, t))
        rows.append((topic, q, a, n))
    order = ["Цена", "Комплектация", "Наличие", "Сроки", "Оплата", "Документы", "Доставка", "Техника", "Навесное", "Сервис", "Процесс"]
    rows.sort(key=lambda r: (order.index(r[0]) if r[0] in order else 99, -r[3]))
    db.execute("DELETE FROM kb_questions"); db.execute("DELETE FROM manager_answers")
    db.executemany("INSERT INTO kb_questions(category,question,best_answer,frequency) VALUES(?,?,?,?)", rows)
    db.executemany("INSERT INTO manager_answers(question,answer,score,comment) VALUES(?,?,?,?)", ANSWERS)
    db.commit()

    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    wb = Workbook(); ws = wb.active; ws.title = "База вопросов"
    ws.append(["Тема", "Вопрос клиента", "Как отвечать", "Обращений с темой"])
    for r in rows: ws.append(list(r))
    ws2 = wb.create_sheet("Разбор ответов")
    ws2.append(["Ситуация", "Что сказал менеджер", "Оценка (1–5)", "Как лучше"])
    for r in ANSWERS: ws2.append(list(r))
    ws3 = wb.create_sheet("Как пользоваться")
    for line in ["База составлена по расшифровкам звонков, комментариям менеджеров в amoCRM (2024–2026) и переписке в WhatsApp, Telegram и MAX через ChatApp (март–ноябрь 2026). Ситуации из переписки на листе «Разбор ответов» отмечены [Переписка].",
                 "«Обращений с темой» — в скольких сделках и чатах тема встречается в комментариях, задачах, звонках или переписке (оценка по ключевым словам).",
                 "Цены в ответах — ориентиры на ноябрь 2026, точную сумму всегда давать в КП.",
                 "Пополняйте базу: новый вопрос — новая строка на листе «База вопросов»."]:
        ws3.append([line])
    for sh, widths in ((ws, [14, 45, 90, 14]), (ws2, [40, 55, 12, 70]), (ws3, [120])):
        for i, w in enumerate(widths): sh.column_dimensions["ABCD"[i]].width = w
        for row in sh.iter_rows():
            for c in row: c.alignment = Alignment(wrap_text=True, vertical="top")
        if sh is not ws3:
            for c in sh[1]: c.font = Font(bold=True); c.fill = PatternFill("solid", fgColor="DDEBE4")
            sh.freeze_panes = "A2"
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    out = os.path.join(ROOT, "reports", "k-truck-knowledge-base.xlsx")
    wb.save(out)
    print(out, len(rows), len(ANSWERS))
    for r in rows: print(r[0], r[3], r[1][:50])


if __name__ == "__main__":
    main()
